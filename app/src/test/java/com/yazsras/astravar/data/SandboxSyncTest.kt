package com.yazsras.astravar.data

import android.content.Context
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.json.JSONObject
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.IOException
import java.util.UUID

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35])
class SandboxSyncTest {
    private lateinit var db: SandboxSyncDb
    private lateinit var api: FakeSandbox
    private lateinit var repo: SandboxSyncRepository
    private val origin = PublicSandbox.DEFAULT_ORIGIN
    @Before fun setup() {
        db = Room.inMemoryDatabaseBuilder(ApplicationProvider.getApplicationContext(), SandboxSyncDb::class.java).build()
        api = FakeSandbox()
        repo = SandboxSyncRepository(db, api)
    }
    @After fun close() { db.close() }

    @Test fun onlyHttpsOriginsWithoutCredentialsPathsPortsOrQueriesAreAccepted() {
        assertEquals(origin, PublicSandbox.origin("$origin/"))
        listOf("http://test.workers.dev", "https://example.com", "$origin/path", "$origin?token=private",
            "https://private@test.workers.dev", "$origin:443", "$origin/#private").forEach { value ->
            try { PublicSandbox.origin(value); fail(value) } catch (_: IllegalArgumentException) {}
        }
    }

    @Test fun canonicalFingerprintMatchesIndependentlyObservedCloudflareReceipt() {
        // Fixed wire fixture from live Worker receipt, not generated by this test's fake server.
        assertEquals("5a03ba85a554c142f1e20a143b1196d0ba5a5a9dd7c48d6449748997e7a655ab",
            PublicSandbox.fingerprint("new_fact", PublicSandbox.templates.getValue("new_fact"), 5))
    }

    @Test fun fixedTemplateQueueContainsNoCampaignRecordsAndUsesExactPublicContract() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        val body = JSONObject(command.body)
        assertEquals(PublicSandbox.CAMPAIGN, body.getString("campaignId"))
        assertEquals(PublicSandbox.CONNECTION, body.getString("connectionId"))
        assertEquals(7, body.length())
        assertEquals(PublicSandbox.templates.getValue("new_fact"), body.getString("detail"))
        assertFalse(command.body.contains("astravar-sandbox-only"))
        assertFalse(command.body.contains("demo-merchant-0001"))
        assertNotNull(UUID.fromString(command.commandId))
        assertEquals("PENDING", repo.commands(origin).first().single().status)
        assertEquals(0, api.posts)
    }

    @Test fun arbitraryMilestoneTextCannotBeQueuedAndSecondPendingCommandIsBlocked() = runBlocking {
        repo.refresh()
        try { repo.queueSynthetic("private campaign prose"); fail() } catch (_: IllegalStateException) {}
        repo.queueSynthetic("agreement")
        try { repo.queueSynthetic("new_fact"); fail() } catch (_: IllegalStateException) {}
        assertEquals(1, repo.commands(origin).first().size)
    }

    @Test fun corruptedOutboxCannotUploadFreeTextOrAdditionalPrivateFields() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        db.sandbox().update(command.copy(body = JSONObject(command.body).put("inventory", "private test sentinel").toString()))
        try { repo.retryPending(); fail() } catch (_: IllegalArgumentException) {}
        assertEquals(0, api.posts)
        assertEquals("PENDING", repo.commands(origin).first().single().status)
    }

    @Test fun committedReceiptAndHistoryReadBackAreVerified() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        repo.retryPending()
        val saved = repo.commands(origin).first().single()
        assertEquals("COMMITTED", saved.status)
        val receipt = JSONObject(saved.receiptJson!!)
        assertEquals(command.commandId, receipt.getString("commandId"))
        assertEquals(command.fingerprint, receipt.getString("payloadFingerprint"))
        assertEquals(receipt.getString("eventId"), repo.events(origin).first().single().eventId)
        assertEquals(2L, repo.endpoint(origin).first()!!.cursor)
    }

    @Test fun offlineQueueSurvivesRepositoryRecreationWithoutNewUuid() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        api.offline = true
        try { repo.retryPending(); fail() } catch (_: IOException) {}
        val after = repo.commands(origin).first().single()
        assertEquals(command.commandId, after.commandId)
        assertEquals(command.body, after.body)
        assertEquals("PENDING", after.status)
        api.offline = false
        repo = SandboxSyncRepository(db, api)
        repo.retryPending()
        assertEquals(command.commandId, repo.commands(origin).first().single().commandId)
        assertEquals(1, api.posts)
    }

    @Test fun lostPostResponseIsRecoveredByReceiptAndNeverPostedTwice() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        api.dropAfterCommit = true
        try { repo.retryPending(); fail() } catch (_: IOException) {}
        assertEquals("PENDING", repo.commands(origin).first().single().status)
        repo = SandboxSyncRepository(db, api)
        repo.retryPending()
        assertEquals(1, api.posts)
        assertEquals(1, api.events.size)
        assertEquals("COMMITTED", repo.commands(origin).first().single().status)
        assertEquals(command.commandId, repo.events(origin).first().single().commandId)
    }

    @Test fun staleRevisionIsRejectedWithoutChangingOrRebasingOriginalCommand() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("agreement")
        api.revision = 2
        try { repo.retryPending(); fail() } catch (e: SandboxFailure) { assertEquals("REVISION_CONFLICT", e.code) }
        val saved = repo.commands(origin).first().single()
        assertEquals("REJECTED", saved.status)
        assertEquals(command.body, saved.body)
        assertEquals(command.expectedRevision, saved.expectedRevision)
        assertEquals(0, api.events.size)
        assertNull(saved.receiptJson)
    }

    @Test fun unmatchingReceiptNeverClaimsRemoteSuccess() = runBlocking {
        repo.refresh()
        repo.queueSynthetic("new_fact")
        api.corruptReceipt = true
        try { repo.retryPending(); fail() } catch (_: IllegalArgumentException) {}
        assertEquals("PENDING", repo.commands(origin).first().single().status)
        assertNull(repo.commands(origin).first().single().receiptJson)
        api.corruptReceipt = false
        repo.retryPending()
        assertEquals("COMMITTED", repo.commands(origin).first().single().status)
        assertEquals(1, api.posts)
    }

    @Test fun originSwitchNeverMovesPendingCommandOrHistory() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        val other = "https://other.synthetic-test.workers.dev"
        repo.configure(other)
        repo.retryPending()
        assertEquals(0, api.posts)
        assertEquals("PENDING", repo.commands(origin).first().single().status)
        assertTrue(repo.commands(other).first().isEmpty())
        repo.configure(origin)
        repo.retryPending()
        assertEquals(command.commandId, repo.commands(origin).first().single().commandId)
        assertEquals(1, api.posts)
    }

    @Test fun paginatedCursorIsDurableAndNeverJumpsOverUnreadEvents() = runBlocking {
        api.addExternalEvent(); api.addExternalEvent(); api.addExternalEvent()
        api.pageSize = 1
        repo.refresh()
        assertEquals(listOf(1L, 2L, 3L), api.cursors)
        assertEquals(4L, repo.endpoint(origin).first()!!.cursor)
        assertEquals(3, repo.events(origin).first().size)
        repo.refresh()
        assertEquals(3, repo.events(origin).first().size)
    }

    @Test fun malformedHistoryPageCannotAdvanceCursorOrPartiallyInsert() = runBlocking {
        api.addExternalEvent(); api.addExternalEvent()
        api.invalidCursor = true
        try { repo.refresh(); fail() } catch (_: IllegalArgumentException) {}
        assertEquals(1L, repo.endpoint(origin).first()!!.cursor)
        assertEquals(0, repo.events(origin).first().size)
    }

    @Test fun quotaFailureKeepsCommandRecoverableAndNeverCreatesAnotherBackend() = runBlocking {
        repo.refresh()
        val command = repo.queueSynthetic("new_fact")
        api.capReached = true
        try { repo.retryPending(); fail() } catch (e: SandboxFailure) { assertEquals(429, e.status) }
        assertEquals("PENDING", repo.commands(origin).first().single().status)
        assertEquals(command.body, repo.commands(origin).first().single().body)
        assertEquals(0, api.events.size)
    }

    @Test fun fileBackedQueueSurvivesDatabaseCloseAndReopen() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<Context>()
        val name = "sandbox-reopen-test.db"
        ctx.deleteDatabase(name)
        var fileDb = Room.databaseBuilder(ctx, SandboxSyncDb::class.java, name).build()
        try {
            var fileRepo = SandboxSyncRepository(fileDb, api)
            fileRepo.refresh()
            val queued = fileRepo.queueSynthetic("new_fact")
            fileDb.close()
            fileDb = Room.databaseBuilder(ctx, SandboxSyncDb::class.java, name).build()
            fileRepo = SandboxSyncRepository(fileDb, api)
            assertEquals(queued, fileRepo.commands(origin).first().single())
            fileRepo.retryPending()
            assertEquals("COMMITTED", fileRepo.commands(origin).first().single().status)
        } finally { fileDb.close(); ctx.deleteDatabase(name) }
    }
}

private class FakeSandbox : SandboxTransport {
    var offline = false
    var dropAfterCommit = false
    var corruptReceipt = false
    var capReached = false
    var invalidCursor = false
    var revision = 1L
    var posts = 0
    var pageSize = 50
    val cursors = mutableListOf<Long>()
    val events = mutableListOf<JSONObject>()
    private val receipts = mutableMapOf<String, JSONObject>()
    private fun scoped() = JSONObject().put("mode", PublicSandbox.MODE)
        .put("campaignId", PublicSandbox.CAMPAIGN).put("connectionId", PublicSandbox.CONNECTION)
    private fun error(status: Int, code: String) = SandboxHttpResponse(status,
        JSONObject().put("mode", PublicSandbox.MODE).put("error", JSONObject().put("code", code).put("message", code)))
    fun addExternalEvent() {
        val command = UUID.randomUUID().toString()
        events += JSONObject().put("eventId", UUID.randomUUID().toString()).put("commandId", command)
            .put("kind", "new_fact").put("detail", "Fictional external test.")
            .put("priorRevision", revision).put("resultingRevision", ++revision).put("recordedAt", "2026-10-18T04:00:00Z")
    }
    override suspend fun request(origin: String, path: String, body: String?): SandboxHttpResponse {
        if (offline) throw IOException("Synthetic offline test")
        if (path == "/health") return SandboxHttpResponse(200,
            JSONObject().put("mode", PublicSandbox.MODE).put("disposable", true).put("authentication", "NONE").put("realCampaignAccess", false))
        if (path == PublicSandbox.BASE) return SandboxHttpResponse(200, scoped().put("disposable", true).put("revision", revision).put("name", "Disposable Test Merchant"))
        if (path.endsWith("/receipt")) {
            val id = path.substringAfter("/commands/").substringBefore("/receipt")
            val receipt = receipts[id] ?: return error(404, "COMMAND_NOT_FOUND")
            return SandboxHttpResponse(200, JSONObject(receipt.toString()).apply { if (corruptReceipt) put("payloadFingerprint", "invalid") })
        }
        if (body != null) {
            posts++
            if (capReached) return error(429, "DAILY_WRITE_CAP")
            val command = JSONObject(body)
            val id = command.getString("commandId")
            receipts[id]?.let { return SandboxHttpResponse(200, it) }
            val prior = command.getLong("expectedRevision")
            if (prior != revision) return error(409, "REVISION_CONFLICT")
            val event = JSONObject().put("eventId", UUID.randomUUID().toString()).put("commandId", id)
                .put("kind", command.getString("kind")).put("detail", command.getString("detail"))
                .put("priorRevision", prior).put("resultingRevision", ++revision).put("recordedAt", "2026-10-18T04:00:00Z")
            events += event
            val receipt = scoped().put("status", "COMMITTED").put("eventId", event.getString("eventId"))
                .put("commandId", id).put("priorRevision", prior).put("resultingRevision", revision)
                .put("recordedAt", event.getString("recordedAt")).put("payloadFingerprint",
                    PublicSandbox.fingerprint(command.getString("kind"), command.getString("detail"), prior))
            receipts[id] = receipt
            if (dropAfterCommit) { dropAfterCommit = false; throw IOException("Simulated lost committed response") }
            return SandboxHttpResponse(200, JSONObject(receipt.toString()).apply { if (corruptReceipt) put("payloadFingerprint", "invalid") })
        }
        if (path.contains("/changes?")) {
            val cursor = path.substringAfter("afterRevision=").substringBefore('&').toLong()
            cursors += cursor
            val unread = events.filter { it.getLong("resultingRevision") > cursor }
            val page = unread.take(pageSize)
            val next = page.lastOrNull()?.getLong("resultingRevision") ?: cursor
            return SandboxHttpResponse(200, scoped().put("currentRevision", revision)
                .put("nextCursor", if (invalidCursor) next + 1 else next).put("hasMore", unread.size > page.size)
                .put("milestones", org.json.JSONArray(page)))
        }
        throw AssertionError("Unexpected synthetic route: $path")
    }
}
